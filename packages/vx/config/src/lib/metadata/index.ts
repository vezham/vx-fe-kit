import {
  existsSync,
  mkdirSync,
  readFileSync,
  watch,
  writeFileSync
} from 'node:fs'
import path from 'node:path'

type VxConfig = {
  core: VxCoreConfig
  branding: {
    themeColor: string
    backgroundColor: string
  }
  pwa: VxPwaConfig
  metadata: VxMetadataConfig
}

type VxCoreConfig = {
  id: string
  name: string
  shortName: string
  version: string
  description: string
  publisher: {
    name: string
    url: string
  }
  url: string
}

type VxPwaConfig = {
  display: string
  orientation: string
  scope: string
  startUrl: string
  categories: string[]
  icons: VxIconSource
  screenshots: VxImage[]
  shortcuts: VxShortcut[]
}

type VxIcon = {
  src: string
  sizes: string
  type: string
}

type VxIconSet = {
  path: string
  sizes: number[]
  type: string
}

type VxIconSource = VxIcon[] | VxIconSet

type VxImage = {
  src: string
  sizes: string
  type: string
}

type VxShortcut = {
  name: string
  shortName: string
  url: string
  icons: VxIconSource
}

type VxMetadataConfig = {
  title: string
  keywords: string[]
  theme: {
    lightColor: string
    darkColor: string
    lightBackgroundColor: string
    darkBackgroundColor: string
  }
  platforms: {
    apple: {
      mobileWebAppCapable: boolean
      webAppCapable: boolean
      touchIcon: string
      startupImages: VxStartupImage[]
    }
    microsoft: {
      startUrl: string
    }
  }
  social: {
    openGraph: {
      type: string
      image: string
    }
    twitter: {
      creator: string
      site: string
      card: string
      image: string
    }
  }
}

type VxStartupImage = {
  colorScheme?: 'light' | 'dark'
  width?: number
  height?: number
  pixelRatio?: number
  path?: string
  media?: string
  src?: string
}

export type GenerateMetadataOptions = {
  projectRoot?: string
  publicDir?: string
}

type MetadataFile = {
  path: string
  content: string
}

const generatedNotice = 'Generated by VX metadata. DO NOT EDIT.'

const readJson = <T>(file: string): T =>
  JSON.parse(readFileSync(file, 'utf8')) as T

const lowerFirst = (value: string) =>
  value ? `${value.charAt(0).toLowerCase()}${value.slice(1)}` : value

const normalizePath = (value: string) => value.split(path.sep).join('/')

const getProjectAssetBaseUrl = (projectRoot: string) =>
  `https://static.cdn.vezham.com/${normalizePath(path.relative(process.cwd(), projectRoot))}`

const createVersionedAssetUrl = (baseUrl: string, version: string) => {
  const versionParam = `vx=${encodeURIComponent(version)}`

  return (assetPath: string) =>
    `${baseUrl.replace(/\/$/, '')}/${assetPath.replace(/^\//, '')}?${versionParam}`
}

const getStaticAssetUrl = (assetPath: string, version: string) =>
  `https://static.cdn.vezham.com/${assetPath.replace(/^\//, '')}?vx=${encodeURIComponent(version)}`

const toAssetUrl = (
  assetPath: string,
  versionedAssetUrl: (assetPath: string) => string
) =>
  /^https?:\/\//.test(assetPath) || assetPath.startsWith('/')
    ? assetPath
    : versionedAssetUrl(assetPath)

const getStartupImageMedia = (image: VxStartupImage) => {
  if (image.media) {
    return image.media
  }

  const colorScheme = image.colorScheme
    ? `(prefers-color-scheme: ${image.colorScheme})`
    : undefined
  const width = image.width ? `(device-width: ${image.width}px)` : undefined
  const height = image.height ? `(device-height: ${image.height}px)` : undefined
  const pixelRatio = image.pixelRatio
    ? `(-webkit-device-pixel-ratio: ${image.pixelRatio})`
    : undefined

  return [colorScheme, width, height, pixelRatio].filter(Boolean).join(' and ')
}

const writeMetadataFile = ({ path: file, content }: MetadataFile) => {
  mkdirSync(path.dirname(file), { recursive: true })
  writeFileSync(file, content)
}

const stringifyManifest = (manifest: Record<string, unknown>) =>
  JSON.stringify(manifest, null, 2).replace(
    '"categories": [\n    "productivity",\n    "personalization",\n    "utilities"\n  ]',
    '"categories": ["productivity", "personalization", "utilities"]'
  )

const stringifyTs = (value: unknown) => JSON.stringify(value, null, 2)

const normalizeIcons = (icons: VxIconSource): VxIcon[] => {
  if (Array.isArray(icons)) {
    return icons
  }

  return icons.sizes.map(size => ({
    src: icons.path.replaceAll('{size}', String(size)),
    sizes: `${size}x${size}`,
    type: icons.type
  }))
}

const getRuntimeMetadata = (config: VxConfig, projectRoot = process.cwd()) => {
  const { core, metadata, pwa } = config
  const { apple, microsoft } = metadata.platforms
  const { openGraph, twitter } = metadata.social
  const versionedAssetUrl = createVersionedAssetUrl(
    getProjectAssetBaseUrl(projectRoot),
    core.version
  )
  const title = metadata.title
  const description = lowerFirst(core.description)
  const lightThemeColor = metadata.theme.lightColor
  const darkThemeColor = metadata.theme.darkColor
  const lightBackgroundColor = metadata.theme.lightBackgroundColor
  const darkBackgroundColor = metadata.theme.darkBackgroundColor
  const faviconLight = versionedAssetUrl('favicon-light.png')
  const faviconDark = versionedAssetUrl('favicon-dark.png')
  const maskIcon = versionedAssetUrl('safari-pinned-tab.svg')
  const appleTouchIcon = versionedAssetUrl(apple.touchIcon)
  const openGraphImage = toAssetUrl(openGraph.image, versionedAssetUrl)
  const twitterImage = toAssetUrl(twitter.image, versionedAssetUrl)
  const startupImages = apple.startupImages.map(image => ({
    media: getStartupImageMedia(image),
    url: toAssetUrl(image.path ?? image.src ?? '', versionedAssetUrl)
  }))

  return {
    title,
    description,
    url: core.url,
    manifest: '/manifest.webmanifest',
    browserConfig: '/browserconfig.xml',
    startUrl: microsoft.startUrl ?? pwa.startUrl,
    author: core.publisher,
    keywords: metadata.keywords,
    theme: {
      lightColor: lightThemeColor,
      darkColor: darkThemeColor,
      lightBackgroundColor,
      darkBackgroundColor
    },
    mobileWebAppCapable: apple.mobileWebAppCapable,
    apple: {
      title: core.name,
      capable: apple.webAppCapable,
      touchIcon: appleTouchIcon,
      startupImages
    },
    icons: {
      faviconLight,
      faviconDark,
      maskIcon
    },
    microsoft: {
      applicationName: core.name,
      config: '/browserconfig.xml',
      startUrl: microsoft.startUrl
    },
    openGraph: {
      type: openGraph.type,
      title: core.name,
      description,
      image: openGraphImage,
      url: core.url
    },
    twitter: {
      creator: twitter.creator,
      site: twitter.site,
      title: core.name,
      description,
      image: twitterImage,
      card: twitter.card
    }
  }
}

